"""Поиск мата по корням слов (ловит формы, приставки, обходы вроде х.у.й и хууууй)."""
import re

# Корни мата (ищем по корню, поэтому ловятся все формы: охуеть, ебанутый, пиздец и т.д.).
# Lookbehind (?<![нлбдр]) нужен, чтобы не ловить обычные слова вроде «хлебать», «небанальный».
BAD_PATTERN = re.compile(
    r"хуй|хуе|хуи|хуя|хую|хуев|хер[ан]?\b|"       # хуй, охуеть, хуёвый, нахуй
    r"пизд|пезд|"                                    # пиздец, пизда, пиздеть
    r"бля[дт]|блеа|"                                 # блять, блядь, блядский
    r"(?<![нлбдр])еб(?:ат|ал|ан|аш|ну|ун|уч|ыр|ис|ло|ли|ля)|"  # ебать, ебанутый, ебало
    r"\bеб[ауое]\b|"                                # еба, ебу
    r"(?:на|за|у|вы|от|по|до|съ|подъ|разъ|объ)еб|"   # наебать, заебал, уебок
    r"муда[кч]|залуп|гондон|пидор|пидар|манда\b"
)

LOOKALIKES = str.maketrans({"x": "х", "y": "у", "e": "е", "a": "а", "o": "о", "p": "р", "c": "с", "b": "б", "ё": "е"})


def has_bad_word(text: str) -> bool:
    t = text.lower().translate(LOOKALIKES)
    t = re.sub(r"[^а-я\s]", "", t)        # убираем знаки, цифры, эмодзи (х*й, б.л.я.т.ь)
    t = re.sub(r"(.)\1+", r"\1", t)        # хуууй -> хуй, блятььь -> блять
    return bool(BAD_PATTERN.search(t))
